import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { capabilityCatalog } from './capabilities.mjs';

export const capabilityHeaderPath = fileURLToPath(new URL('../../Source/RmlUiUnrealJS/Private/RmlUiCapabilityCatalog.inl', import.meta.url));

export function generateCapabilityHeader(catalog = capabilityCatalog) {
  const condition = features => [...features].sort().map(feature => `Feature == TEXT("${feature}")`).join(' ||\n        ') || 'false';
  return `// Generated by Tools/src/generate-capability-catalog.mjs. Do not edit manually.\n#pragma once\n\n#include "CoreMinimal.h"\n\n` +
    `inline constexpr uint32 RmlUiCapabilitySchemaVersion = ${catalog.schemaVersion}u;\n` +
    `inline constexpr uint32 RmlUiMinimumHostAbi = ${catalog.minimumHostAbi}u;\n` +
    `inline constexpr uint32 RmlUiMinimumSlateAbi = ${catalog.profiles['slate-rhi'].minimumSlateAbi}u;\n\n` +
    `inline bool RmlUiKnownFeature(const FString& Feature)\n{\n    return ${condition(Object.keys(catalog.features))};\n}\n\n` +
    `inline bool RmlUiProfileHasFeature(const FString& Profile, const FString& Feature)\n{\n` +
    Object.entries(catalog.profiles).filter(([, profile]) => !profile.deprecated).sort(([a], [b]) => a.localeCompare(b)).map(([name, profile]) =>
      `    if (Profile == TEXT("${name}"))\n        return ${condition(profile.features)};\n`).join('') +
    `    return false;\n}\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const header = generateCapabilityHeader();
  let previous = '';
  try { previous = await readFile(capabilityHeaderPath, 'utf8'); } catch { /* First generation. */ }
  if (previous !== header) await writeFile(capabilityHeaderPath, header, 'utf8');
}
