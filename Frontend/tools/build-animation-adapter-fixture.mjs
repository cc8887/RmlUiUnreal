import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { build } from 'esbuild';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const animationAdapterFixturePath = path.resolve(
  root,
  '../Content/RmlUi/Tests/animation-adapter-puerts-fixture.js',
);
export const animationCompletionBurstFixturePath = path.resolve(
  root,
  '../Content/RmlUi/Tests/animation-completion-burst-puerts-fixture.js',
);
export const animationPlanCacheWorkloadFixturePath = path.resolve(
  root,
  '../Content/RmlUi/Tests/animation-plan-cache-workload-puerts-fixture.js',
);

async function bundleFixture(entryPoint) {
  const result = await build({
    entryPoints: [path.join(root, entryPoint)],
    bundle: true,
    write: false,
    platform: 'neutral',
    format: 'cjs',
    target: 'es2020',
    legalComments: 'none',
    external: ['puerts'],
    plugins: [{
      name: 'rmlui-puerts-bridge',
      setup(builder) {
        builder.onResolve({ filter: /bridge$/ }, () => ({ path: 'bridge', namespace: 'rmlui-fixture' }));
        builder.onLoad({ filter: /^bridge$/, namespace: 'rmlui-fixture' }, () => ({
          contents: [
            "export const native = require('puerts').argv.getByName('bridge');",
            "export function check(result) { if (!result) throw new Error(native.LastError || 'RmlUi native operation failed'); }",
            "export function report(error) { native.ReportError(error instanceof Error ? error.stack || error.message : String(error)); }",
          ].join('\n'),
          loader: 'js',
        }));
      },
    }],
  });
  return `// Generated by Frontend/tools/build-animation-adapter-fixture.mjs.\n${result.outputFiles[0].text}`;
}

export async function buildAnimationAdapterFixture({ write = true } = {}) {
  const generated = await bundleFixture('tests/fixtures/animation-adapter-puerts-entry.ts');
  if (write) {
    await mkdir(path.dirname(animationAdapterFixturePath), { recursive: true });
    await writeFile(animationAdapterFixturePath, generated);
  }
  return generated;
}

export async function buildAnimationCompletionBurstFixture({ write = true } = {}) {
  const generated = await bundleFixture('tests/fixtures/animation-completion-burst-puerts-entry.ts');
  if (write) {
    await mkdir(path.dirname(animationCompletionBurstFixturePath), { recursive: true });
    await writeFile(animationCompletionBurstFixturePath, generated);
  }
  return generated;
}

export async function buildAnimationPlanCacheWorkloadFixture({ write = true } = {}) {
  const generated = await bundleFixture('tests/fixtures/animation-plan-cache-workload-puerts-entry.ts');
  if (write) {
    await mkdir(path.dirname(animationPlanCacheWorkloadFixturePath), { recursive: true });
    await writeFile(animationPlanCacheWorkloadFixturePath, generated);
  }
  return generated;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const [adapterExpected, adapterActual, burstExpected, burstActual, workloadExpected, workloadActual] = await Promise.all([
      buildAnimationAdapterFixture({ write: false }),
      readFile(animationAdapterFixturePath, 'utf8'),
      buildAnimationCompletionBurstFixture({ write: false }),
      readFile(animationCompletionBurstFixturePath, 'utf8'),
      buildAnimationPlanCacheWorkloadFixture({ write: false }),
      readFile(animationPlanCacheWorkloadFixturePath, 'utf8'),
    ]);
    if (adapterActual !== adapterExpected)
      throw new Error(`Generated fixture is stale: ${animationAdapterFixturePath}`);
    if (burstActual !== burstExpected)
      throw new Error(`Generated fixture is stale: ${animationCompletionBurstFixturePath}`);
    if (workloadActual !== workloadExpected)
      throw new Error(`Generated fixture is stale: ${animationPlanCacheWorkloadFixturePath}`);
  } else {
    await Promise.all([
      buildAnimationAdapterFixture(),
      buildAnimationCompletionBurstFixture(),
      buildAnimationPlanCacheWorkloadFixture(),
    ]);
    console.log(`Built Puerts animation fixtures: ${animationAdapterFixturePath}, ${animationCompletionBurstFixturePath}, ${animationPlanCacheWorkloadFixturePath}`);
  }
}
